"""Ed25519 signing for the mutation-log audit chain (0.6.6+).

Layer above the SHA-256 hash chain in mutation_log.py. The hash chain catches
casual tampering (someone deletes or modifies events without recomputing).
Ed25519 closes the *chain rewrite* gap — an adversary with full filesystem
write access could otherwise delete an event, recompute all downstream
prev_hash values, and the chain would re-validate. With Ed25519, every event
is also signed; an adversary who doesn't have the private key cannot forge
valid signatures, so rewrites are detectable.

Key layout (0.6.8 B4 — per-host namespacing):

    ~/.workspace/keys/<host_id>/identity.priv    # operator key (per host)
    ~/.workspace/keys/<host_id>/identity.pub
    ~/.workspace/keys/controller.priv            # controller key (per workspace, NOT per host)
    ~/.workspace/keys/controller.pub

``host_id`` is the first 12 hex chars of ``sha256(hostname + "|" + machine_id)``.
Stable across reboots, distinct across hosts that share a homedir (NFS, MSP).

The controller key is a SEPARATE key used as a co-signer for high-stakes
operations (purge tombstones, erasure). It is workspace-scoped, not
host-scoped — the legal controller is the same entity regardless of which
host performed the action. Generated by the explicit ``workspaces keys
init-controller`` ceremony, never auto-created on first use.

Override the key root via the ``WORKSPACE_KEY_DIR`` env var.

Backward compat: events written before 0.6.6 lack a signature. Verification
accepts them but counts them as ``unsigned_events`` in the chain result.
Existing single-key installs (keys at the flat root, pre-0.6.8) are migrated
to the host-scoped layout on first call via
``migrate_legacy_keypair_to_host_subdir()`` — see B4 in the release plan.
"""

from __future__ import annotations

import hashlib
import logging
import os
import socket
import stat
import subprocess
from pathlib import Path
from typing import Optional

from cryptography.hazmat.primitives.asymmetric.ed25519 import (
    Ed25519PrivateKey,
    Ed25519PublicKey,
)
from cryptography.hazmat.primitives import serialization
from cryptography.exceptions import InvalidSignature


_log = logging.getLogger(__name__)

DEFAULT_KEY_DIR = Path.home() / ".workspace" / "keys"
"""Default location of the key tree root. Override via WORKSPACE_KEY_DIR env.

After 0.6.8 B4 this is the *root*; identity keys live in
``<root>/<host_id>/identity.{priv,pub}`` and the controller keypair lives
flat at ``<root>/controller.{priv,pub}``.
"""


def _key_root_dir() -> Path:
    """Resolve the active key root (env override > default).

    The root is the top-level directory; per-host subdirectories sit under
    this and the controller keypair sits flat at the root.
    """
    override = os.environ.get("WORKSPACE_KEY_DIR")
    return Path(override).expanduser() if override else DEFAULT_KEY_DIR


KEY_PASSPHRASE_ENV = "WORKSPACE_KEY_PASSPHRASE"
"""Passphrase for private keys at rest. When set, new private keys are
written passphrase-encrypted (PKCS8 BestAvailableEncryption) and encrypted
keys load with it; when unset, keys are written cleartext and filesystem
permissions (0600) are the only protection. Verification paths read the
``.pub`` files and never need the passphrase."""


def _key_encryption() -> serialization.KeySerializationEncryption:
    pw = os.environ.get(KEY_PASSPHRASE_ENV)
    return (serialization.BestAvailableEncryption(pw.encode())
            if pw else serialization.NoEncryption())


def _load_private_key(pem: bytes, path: Path) -> object:
    """Load a PEM private key written in either at-rest mode.

    Cleartext loads directly; an encrypted key loads with the passphrase
    from ``WORKSPACE_KEY_PASSPHRASE``. Raises ``RuntimeError`` naming the
    env var when the key is encrypted and no (or the wrong) passphrase is
    available — a signing path must fail loud, not fall through to a fresh
    identity."""
    try:
        return serialization.load_pem_private_key(pem, password=None)
    except TypeError:
        pw = os.environ.get(KEY_PASSPHRASE_ENV)
        if not pw:
            raise RuntimeError(
                f"private key at {path} is passphrase-protected; set "
                f"{KEY_PASSPHRASE_ENV} to load it"
            ) from None
        try:
            return serialization.load_pem_private_key(pem, password=pw.encode())
        except ValueError as e:
            raise RuntimeError(
                f"private key at {path} did not decrypt with the passphrase "
                f"from {KEY_PASSPHRASE_ENV}: {e}"
            ) from None


# ---------------------------------------------------------------------------
# Host identity (0.6.8 B4)
# ---------------------------------------------------------------------------


def _machine_id() -> str:
    """Best-effort stable machine identifier.

    Order of preference:
      1. ``/etc/machine-id`` (systemd-style; Linux default).
      2. ``/var/lib/dbus/machine-id`` (older Linux fallback).
      3. macOS ``IOPlatformUUID`` via ``ioreg``.
      4. The literal ``"no-machine-id"`` — stable but generic; on platforms
         where we can't probe, hosts that share a homedir will collide.
         Acceptable because hostname still differs in most realistic setups.

    Never raises; failure modes degrade to the constant fallback.
    """
    # Linux paths.
    for p in ("/etc/machine-id", "/var/lib/dbus/machine-id"):
        try:
            data = Path(p).read_text(encoding="utf-8").strip()
            if data:
                return data
        except (OSError, UnicodeDecodeError):
            continue
    # macOS: parse `ioreg -rd1 -c IOPlatformExpertDevice`.
    try:
        out = subprocess.check_output(
            ["ioreg", "-rd1", "-c", "IOPlatformExpertDevice"],
            stderr=subprocess.DEVNULL,
            timeout=2,
        ).decode("utf-8", errors="ignore")
        # Find IOPlatformUUID line: `    "IOPlatformUUID" = "ABCD-..."`
        for line in out.splitlines():
            if "IOPlatformUUID" in line and "=" in line:
                # Extract the quoted value.
                _, _, rhs = line.partition("=")
                rhs = rhs.strip()
                if rhs.startswith('"') and rhs.endswith('"'):
                    val = rhs[1:-1].strip()
                    if val:
                        return val
    except (OSError, subprocess.SubprocessError, subprocess.TimeoutExpired) as e:
        # Documented degrade path ("never raises") — but not silent.
        _log.debug("machine-id probe via ioreg failed: %s", e)
    return "no-machine-id"


HOST_ID_ENV = "WORKSPACE_HOST_ID"
"""Explicit host-identity override. When set, it pins ``host_id`` regardless of the
machine hostname — the recovery/portability path for issue #122. An operator who moved
networks (changing ``socket.gethostname()``) can set this to the host_id that signed an
existing chain to make it verify again."""


def _host_id_pin_path() -> Path:
    """Where the resolved host_id is persisted so it never drifts with the hostname."""
    return _key_root_dir() / "host-id"


def _host_id() -> str:
    """Stable 12-char host identity.

    Resolution order — every branch is stable across reboots AND hostname/network
    changes:
      1. ``WORKSPACE_HOST_ID`` env — explicit override (recovery / portability).
      2. The persisted pin at ``<key-root>/host-id`` — written the first time an id is
         derived, and read verbatim thereafter.
      3. Derive ``sha256(hostname + "|" + machine_id)[:12]`` and persist it to (2).

    Before this pin, the function returned (3) directly. That is NOT stable when the OS
    hostname tracks the network (e.g. macOS with ``HostName`` unset): a chain signed
    under one hostname then failed verification after the machine moved networks and a
    different key was loaded — issue #122. Pinning (1)/(2) fixes that; ``machine_id``
    was already stable, so the hostname was the only moving part.
    """
    env = os.environ.get(HOST_ID_ENV)
    if env and env.strip():
        return env.strip()
    pin = _host_id_pin_path()
    try:
        if pin.is_file():
            pinned = pin.read_text(encoding="utf-8").strip()
            if pinned:
                return pinned
    except OSError:
        pass  # unreadable pin (perms/IO) -> fall through and derive fresh below
    h = socket.gethostname() or "unknown-host"
    m = _machine_id() or "no-machine-id"
    hid = hashlib.sha256(f"{h}|{m}".encode("utf-8")).hexdigest()[:12]
    try:
        pin.parent.mkdir(parents=True, exist_ok=True)
        pin.write_text(hid + "\n", encoding="utf-8")
    except OSError:
        pass  # persistence is best-effort; the derived id still holds this run
    return hid


def _key_dir() -> Path:
    """Active per-host key directory (0.6.8+).

    Returns ``<root>/<host_id>``. Pre-0.6.8 code called this directly to get
    the flat root; callers expecting the legacy shape will read keys from a
    location that no longer matches what a fresh install creates. Use the
    migration helper to bring legacy layouts forward.
    """
    return _key_root_dir() / _host_id()


def _private_key_path() -> Path:
    return _key_dir() / "identity.priv"


def _public_key_path() -> Path:
    return _key_dir() / "identity.pub"


