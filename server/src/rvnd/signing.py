# Controller key (0.6.8 B4 / D2)
# ---------------------------------------------------------------------------


def _controller_key_dir() -> Path:
    """Controller key directory.

    The controller key is workspace-scoped, NOT per-host, so it sits flat at
    the key root — the same controller signs from every host they touch.
    """
    return _key_root_dir()


def _controller_private_key_path() -> Path:
    return _controller_key_dir() / "controller.priv"


def _controller_public_key_path() -> Path:
    return _controller_key_dir() / "controller.pub"


def ensure_keypair() -> tuple[Ed25519PrivateKey, Ed25519PublicKey]:
    """Return (private, public). Generates a new keypair on first call.

    Private key file is written with 0600 permissions. The public key sits
    alongside it for sharing/verification by third parties.

    Idempotent: subsequent calls load the existing keypair.

    0.6.8 migration: if a pre-0.6.8 keypair is sitting at the FLAT root (no
    per-host subdir), it is silently auto-migrated into the per-host subdir
    on first access here. Operators who want the explicit, audit-logged
    migration should call ``migrate_legacy_keypair_to_host_subdir(audit_log=...)``
    directly — that path writes a chain breadcrumb; this auto-path does not.
    """
    kd = _key_dir()
    priv_path = _private_key_path()
    pub_path = _public_key_path()

    # Auto-migrate from the legacy flat-root location if needed (silent;
    # no audit event — see docstring).
    legacy_priv = _key_root_dir() / "identity.priv"
    legacy_pub = _key_root_dir() / "identity.pub"
    if not priv_path.exists() and legacy_priv.exists():
        kd.mkdir(parents=True, exist_ok=True)
        try:
            os.replace(legacy_priv, priv_path)
            if legacy_pub.exists():
                os.replace(legacy_pub, pub_path)
            try:
                os.chmod(priv_path, stat.S_IRUSR | stat.S_IWUSR)
            except OSError as e:
                _log.debug("chmod 0600 on %s failed (best-effort): %s",
                           priv_path, e)
        except OSError as e:
            # Integrity-relevant: a silent failure here falls through to
            # generating a NEW host identity key — a silent identity change
            # on the signing path. Surface it.
            _log.warning(
                "legacy key migration %s -> %s failed (%s); a new host key "
                "will be generated if none exists at the target",
                legacy_priv, priv_path, e,
            )

    if priv_path.exists():
        priv_bytes = priv_path.read_bytes()
        priv = _load_private_key(priv_bytes, priv_path)
        if not isinstance(priv, Ed25519PrivateKey):
            raise TypeError(
                f"key at {priv_path} is not an Ed25519 private key"
            )
        pub = priv.public_key()
        return priv, pub

    # Fresh generation — atomic first-writer-wins. Two processes racing the
    # first signature used to both pass the exists() check above, both
    # generate, and last-write-win the file; each would then RETURN ITS OWN
    # key, so the loser signed events with a key that was never on disk and
    # verify_chain reported signature failures. The candidate key is written
    # to a unique temp name and the canonical path is claimed with a hard
    # link (atomic create-if-absent); the loser discards its candidate and
    # loads the winner's key. Readers can never observe a partial private
    # key: the canonical name only ever points at fully written bytes.
    kd.mkdir(parents=True, exist_ok=True)
    priv = Ed25519PrivateKey.generate()
    pub = priv.public_key()

    priv_pem = priv.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=_key_encryption(),
    )
    pub_pem = pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    tmp = priv_path.with_name(f".{priv_path.name}.tmp.{os.getpid()}")
    tmp.write_bytes(priv_pem)
    try:
        os.chmod(tmp, stat.S_IRUSR | stat.S_IWUSR)  # 0600 before it's visible
    except OSError as e:
        _log.debug("chmod 0600 on %s failed (best-effort): %s", tmp, e)
    try:
        os.link(tmp, priv_path)
    except FileExistsError:
        # Lost the race: a concurrent first-caller claimed the identity.
        tmp.unlink(missing_ok=True)
        winner = _load_private_key(priv_path.read_bytes(), priv_path)
        if not isinstance(winner, Ed25519PrivateKey):
            raise TypeError(f"key at {priv_path} is not an Ed25519 private key")
        return winner, winner.public_key()
    except OSError as e:
        # Filesystem without hard links: degrade to a plain move. Non-atomic
        # against a concurrent winner, but no worse than the pre-fix path.
        _log.debug("hard-link claim unavailable (%s); using os.replace", e)
        os.replace(tmp, priv_path)
    else:
        tmp.unlink(missing_ok=True)
    pub_path.write_bytes(pub_pem)

    return priv, pub


def sign_bytes(data: bytes, private_key: Optional[Ed25519PrivateKey] = None) -> str:
    """Sign data and return a hex-encoded signature. Uses default keypair if none provided."""
    if private_key is None:
        private_key, _ = ensure_keypair()
    return private_key.sign(data).hex()


def verify_signature(
    data: bytes,
    signature_hex: str,
    public_key: Optional[Ed25519PublicKey] = None,
) -> bool:
    """Verify a hex-encoded signature against data. Uses default keypair's public if none provided."""
    if public_key is None:
        _, public_key = ensure_keypair()
    try:
        public_key.verify(bytes.fromhex(signature_hex), data)
        return True
    except (InvalidSignature, ValueError):
        return False


def public_key_pem() -> str:
    """Return the active public key in PEM format (for sharing / publication)."""
    _, pub = ensure_keypair()
    return pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    ).decode("utf-8")


def public_key_fingerprint() -> str:
    """First 16 hex chars of sha256 of the active identity public key bytes.

    Surfaced in ``workspaces status`` so an operator can spot-check that two
    hosts are running the keys they think they're running, and that key
    rotation actually changed something.
    """
    _, pub = ensure_keypair()
    return fingerprint_of(pub)[:16]


def fingerprint_of(pub: Ed25519PublicKey) -> str:
    """Full sha256 hex of an Ed25519 public key's raw bytes — the stable
    identifier a chain pins to (see genesis key registration)."""
    raw = pub.public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )
    return hashlib.sha256(raw).hexdigest()


def identity_fingerprint_or_none() -> Optional[str]:
    """Fingerprint of this host's on-disk identity public key, WITHOUT
    generating one. ``None`` if no keypair exists yet. Read-only: safe on
    verification paths."""
    pub = identity_public_key_or_none()
    return fingerprint_of(pub) if pub is not None else None


def identity_public_pem_or_none() -> Optional[str]:
    """PEM of this host's on-disk identity public key, without generating.
    ``None`` if absent. Embedded in a genesis key_registration event so a
    verifier can recover the pinned key from the chain itself."""
    pub = identity_public_key_or_none()
    if pub is None:
        return None
    return pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    ).decode("utf-8")


def register_identity() -> tuple[str, str]:
    """Ensure the identity keypair exists and return (fingerprint, PEM) for a
    genesis key_registration. Unlike the ``*_or_none`` readers this is a write
    path — pinning a chain generates the key it commits to if none exists yet."""
    _, pub = ensure_keypair()
    pem = pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    ).decode("utf-8")
    return fingerprint_of(pub), pem


