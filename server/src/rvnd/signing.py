def migrate_legacy_keypair_to_host_subdir(
    *,
    audit_log: "object | None" = None,
) -> str:
    """Move a pre-0.6.8 flat-root keypair into the per-host subdirectory.

    Pre-0.6.8 layout (flat):

        <root>/identity.priv
        <root>/identity.pub

    Post-0.6.8 layout (per-host):

        <root>/<host_id>/identity.priv
        <root>/<host_id>/identity.pub

    Behaviour:
      - If the flat-root keypair exists OUTSIDE a host subdir, atomically
        move it into ``<root>/<host_id>/``. Returns the active 12-char
        ``host_id`` either way (the caller usually wants to print it).
      - If no legacy keypair exists (fresh install, or migration already
        ran), returns the active ``host_id`` and writes no audit event.
      - If ``audit_log`` is provided (a ``MutationLog`` instance), the
        migration emits a ``system`` event with ``extra.kind="key_migration"``
        so the chain is honest about the change.

    Idempotent: second call is a no-op (the legacy file is gone after the
    first call moved it).

    Atomic-ish: uses ``os.replace`` so a crash mid-move can't leave the
    keypair in both locations.
    """
    root = _key_root_dir()
    host_id = _host_id()

    legacy_priv = root / "identity.priv"
    legacy_pub = root / "identity.pub"

    if not legacy_priv.exists() and not legacy_pub.exists():
        return host_id  # nothing to migrate; fresh install or already-migrated

    target_dir = root / host_id
    target_dir.mkdir(parents=True, exist_ok=True)
    target_priv = target_dir / "identity.priv"
    target_pub = target_dir / "identity.pub"

    # If the target already exists, refuse to clobber — operator should
    # resolve manually (might be a fresh host-scoped key generated alongside
    # an un-cleaned legacy keypair).
    if target_priv.exists() or target_pub.exists():
        # Treat as already-migrated for the purposes of returning host_id.
        # If the legacy files are stragglers (target also exists), we leave
        # them in place so the operator notices.
        return host_id

    # Atomic-ish move (rename within the same filesystem).
    moved_from_priv: str | None = None
    moved_from_pub: str | None = None
    if legacy_priv.exists():
        os.replace(legacy_priv, target_priv)
        moved_from_priv = str(legacy_priv)
        try:
            os.chmod(target_priv, stat.S_IRUSR | stat.S_IWUSR)  # 0600
        except OSError as e:
            _log.debug("chmod 0600 on %s failed (best-effort): %s",
                       target_priv, e)
    if legacy_pub.exists():
        os.replace(legacy_pub, target_pub)
        moved_from_pub = str(legacy_pub)

    # Emit an audit-chain breadcrumb if a log was provided.
    if audit_log is not None and (moved_from_priv or moved_from_pub):
        try:
            from .mutation_log import LogEvent  # local import — avoid cycle at import time
            event = LogEvent(
                event="system",
                folder_path=str(getattr(audit_log, "folder_path", "")),
                pair_id=f"key-migration:{host_id}",
                channel="system",
                actor="system:key_migration",
                extra={
                    "kind": "key_migration",
                    "from_path": moved_from_priv or moved_from_pub or "",
                    "to_path": str(target_priv),
                    "host_id": host_id,
                },
            )
            audit_log.append(event)
        except Exception:
            # Best-effort — the migration itself succeeded; failing to log it
            # is loud-noticeable in `workspaces status` chain stats but shouldn't
            # roll back the move.
            pass

    return host_id
