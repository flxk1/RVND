def ensure_controller_keypair() -> tuple[Ed25519PrivateKey, Ed25519PublicKey]:
    """Return (private, public) for the controller key.

    Unlike ``ensure_keypair()``, this is the LEGAL controller's co-signing
    key — used to authorise high-stakes operations (purge tombstones, B5
    erasure). One controller key per workspace; the same key signs from
    every host the controller touches.

    Idempotent: subsequent calls load the existing keypair. Generated on
    first call (or via the explicit ``workspaces keys init-controller``
    ceremony — see ``cli.py``).
    """
    kd = _controller_key_dir()
    priv_path = _controller_private_key_path()
    pub_path = _controller_public_key_path()

    if priv_path.exists():
        priv_bytes = priv_path.read_bytes()
        priv = _load_private_key(priv_bytes, priv_path)
        if not isinstance(priv, Ed25519PrivateKey):
            raise TypeError(
                f"key at {priv_path} is not an Ed25519 private key"
            )
        pub = priv.public_key()
        return priv, pub

    kd.mkdir(parents=True, exist_ok=True)
    priv = Ed25519PrivateKey.generate()
    pub = priv.public_key()

    priv_pem = priv.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=_key_encryption(),
    )
    pub_pem = pub.public_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PublicFormat.SubjectPublicKeyInfo,
    )
    priv_path.write_bytes(priv_pem)
    pub_path.write_bytes(pub_pem)
    try:
        os.chmod(priv_path, stat.S_IRUSR | stat.S_IWUSR)  # 0600
    except OSError as e:
        _log.debug("chmod 0600 on %s failed (best-effort): %s", priv_path, e)
    return priv, pub


def sign_with_controller(data: bytes) -> str:
    """Sign ``data`` with the controller key. Returns hex-encoded signature.

    Generates the controller keypair on first use. For high-stakes flows
    (B1 purge tombstone, B5 erasure) the operator key signature is
    co-required with this one.
    """
    priv, _ = ensure_controller_keypair()
    return priv.sign(data).hex()


def verify_controller_signature(data: bytes, signature_hex: str) -> bool:
    """Verify ``signature_hex`` over ``data`` against the controller pubkey."""
    _, pub = ensure_controller_keypair()
    try:
        pub.verify(bytes.fromhex(signature_hex), data)
        return True
    except (InvalidSignature, ValueError):
        return False


def identity_public_key_or_none() -> Optional[Ed25519PublicKey]:
    """Load this host's identity PUBLIC key from disk WITHOUT creating it.

    Read-only counterpart of :func:`ensure_keypair` for verification paths:
    reads ``identity.pub`` only, so it needs neither write access nor the
    key passphrase. Returns ``None`` when no keypair exists yet."""
    try:
        pub_path = _public_key_path()
        if pub_path.exists():
            pub = serialization.load_pem_public_key(pub_path.read_bytes())
            if isinstance(pub, Ed25519PublicKey):
                return pub
    except Exception:
        return None
    return None


def controller_public_key_or_none() -> Optional[Ed25519PublicKey]:
    """Load the controller PUBLIC key from disk WITHOUT creating it.

    Returns ``None`` when no controller key is registered. Unlike
    :func:`verify_controller_signature` (which calls
    ``ensure_controller_keypair`` and would auto-generate), this is safe to
    call from read-only paths such as ``verify_chain`` — it never writes.
    """
    priv_path = _controller_private_key_path()
    pub_path = _controller_public_key_path()
    # Read the .pub first: it is always cleartext, so verification works
    # without the key passphrase (and without touching the private key).
    try:
        if pub_path.exists():
            pub = serialization.load_pem_public_key(pub_path.read_bytes())
            if isinstance(pub, Ed25519PublicKey):
                return pub
        if priv_path.exists():
            priv = _load_private_key(priv_path.read_bytes(), priv_path)
            if isinstance(priv, Ed25519PrivateKey):
                return priv.public_key()
    except Exception:
        return None
    return None


def verify_controller_signature_strict(data: bytes, signature_hex: str) -> bool:
    """Verify a controller signature against the on-disk controller pubkey.

    Returns ``False`` (never auto-creates) if no controller key is registered
    or the signature does not validate. Used by ``verify_chain`` to enforce
    two-key purge tombstones: a tombstone that *claims* controller
    co-signature must validate against the registered controller pubkey or it
    is treated as a forgery.
    """
    pub = controller_public_key_or_none()
    if pub is None:
        return False
    try:
        pub.verify(bytes.fromhex(signature_hex), data)
        return True
    except (InvalidSignature, ValueError):
        return False


def public_controller_key_fingerprint() -> str | None:
    """16-hex-char fingerprint of the controller public key, or None.

    Returns ``None`` if the controller keypair has not been initialised yet
    (operator has not run ``workspaces keys init-controller``). Surfaces in
    ``workspaces status`` as ``(none)`` when this is None.
    """
    if not _controller_private_key_path().exists():
        return None
    _, pub = ensure_controller_keypair()
    raw = pub.public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )
    return hashlib.sha256(raw).hexdigest()[:16]


